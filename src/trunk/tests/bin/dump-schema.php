<?php
/**
 * Freezes the current schema into tests/schema/v<DB_VERSION>.sql.
 *
 * Every DB_VERSION bump ships a new snapshot: the convergence test replays each of them and
 * asserts that upgrading from it lands on exactly what a fresh install produces. A version with no
 * snapshot is a version nothing verifies.
 *
 * The snapshot is generated from the real MySQL rather than hand-written from the activators'
 * CREATE TABLE strings, because those two are not the same thing — dbDelta and MySQL both
 * normalize (types, index order, charset), and it is the normalized result an upgrade has to
 * converge to. Table names carry a {PREFIX} placeholder the tests substitute.
 *
 * Run inside the `wordpress` dev container, from the plugin directory:
 *
 *     docker compose exec -T -w /var/www/html/wp-content/plugins/paycrypto-me-for-woocommerce \
 *         wordpress php tests/bin/dump-schema.php
 *
 * Precedent: tests/bin/generate_vectors.php.
 */

if (PHP_SAPI !== 'cli') {
    fwrite(STDERR, "CLI only.\n");
    exit(1);
}

if (!defined('WP_USE_THEMES')) {
    define('WP_USE_THEMES', false);
}

$wp_load = getenv('PAYCRYPTO_WP_LOAD') ?: '/var/www/html/wp-load.php';

if (!file_exists($wp_load)) {
    fwrite(STDERR, "WordPress not found at {$wp_load} — run this inside the `wordpress` container.\n");
    exit(1);
}

require $wp_load;
require_once ABSPATH . 'wp-admin/includes/upgrade.php';
require_once dirname(__DIR__, 2) . '/vendor/autoload.php';

use PayCryptoMe\WooCommerce\DbInstaller;
use PayCryptoMe\WooCommerce\PayCryptoMeBitcoinGatewayActivate;
use PayCryptoMe\WooCommerce\PayCryptoMeLightningGatewayActivate;

global $wpdb;

$tables = [
    'paycrypto_me_bitcoin_wallet_xpubkeys',
    'paycrypto_me_bitcoin_derivation_indexes',
    'paycrypto_me_bitcoin_transactions_data',
    'paycrypto_me_lightning_invoices',
];

$version = $argv[1] ?? DbInstaller::DB_VERSION;
$prefix  = 'pcmdump_';
$target  = dirname(__DIR__) . '/schema/v' . $version . '.sql';

if (file_exists($target)) {
    fwrite(STDERR, "Refusing to overwrite {$target}. A frozen snapshot describes a released schema;\n");
    fwrite(STDERR, "if it is genuinely wrong, delete it deliberately and re-run.\n");
    exit(1);
}

$original_prefix = $wpdb->prefix;
$wpdb->prefix = $prefix;

foreach ($tables as $table) {
    $wpdb->query("DROP TABLE IF EXISTS `{$prefix}{$table}`");
}

// The activators, not install(): this must not touch the site's recorded schema version.
$errors = array_merge(
    PayCryptoMeBitcoinGatewayActivate::activate(),
    PayCryptoMeLightningGatewayActivate::activate()
);

if ($errors) {
    fwrite(STDERR, "Activation errors, refusing to freeze a broken schema:\n  " . implode("\n  ", $errors) . "\n");
    exit(1);
}

$lines = [
    '-- Frozen schema for DB_VERSION ' . $version . '.',
    '-- Generated by tests/bin/dump-schema.php from the real MySQL, not hand-written.',
    '-- {PREFIX} is substituted by SchemaTestCase::install_frozen_schema().',
    '-- Do not edit: this describes a schema that shipped, so changing it rewrites history.',
    '',
];

foreach ($tables as $table) {
    $row = $wpdb->get_row("SHOW CREATE TABLE `{$prefix}{$table}`", ARRAY_N);

    if (!$row) {
        fwrite(STDERR, "Table {$prefix}{$table} was not created.\n");
        exit(1);
    }

    // AUTO_INCREMENT= is per-table state, not schema, and would make the snapshot depend on how
    // many rows happened to exist when it was taken.
    $ddl = (string) preg_replace('/ AUTO_INCREMENT=\d+/', '', $row[1]);
    $ddl = str_replace('`' . $prefix, '`{PREFIX}', $ddl);

    $lines[] = $ddl . ";\n";
}

foreach ($tables as $table) {
    $wpdb->query("DROP TABLE IF EXISTS `{$prefix}{$table}`");
}

$wpdb->prefix = $original_prefix;

if (!is_dir(dirname($target)) && !mkdir(dirname($target), 0o755, true)) {
    fwrite(STDERR, "Could not create " . dirname($target) . "\n");
    exit(1);
}

file_put_contents($target, implode("\n", $lines));

echo "Wrote {$target}\n";
